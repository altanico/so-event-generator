const ENV = require('./_env.js');
// CSAR / MEDEVAC: prepared scenarios, PR pack, assignment, nothing secret in pilot outputs
const { chromium } = require(ENV.PW); const { execSync } = require('child_process');
(async()=>{const b=await chromium.launch({executablePath:ENV.CHROME,args:['--no-sandbox']});
const ctx=await b.newContext({acceptDownloads:true,viewport:{width:1300,height:900}});const page=await ctx.newPage();const errs=[];
page.on('pageerror',e=>errs.push('PAGEERR '+e.message));
await page.route('**/*',r=>{const u=r.request().url();
 if(u.includes('leaflet.min.js'))return r.fulfill({path:ENV.LMOCK});
 if(u.includes('pptxgen'))return r.fulfill({path:ENV.PPTX});
 if(u.includes('pdf-lib.min.js'))return r.fulfill({path:ENV.PDFLIB});
 if(u.startsWith(ENV.BASE))return r.continue(); return r.abort();});
await page.goto(ENV.BASE+'/index.html#staff'); await page.waitForTimeout(800);
const fail=[];
const pre=await page.evaluate(()=>{ APP.S=JSON.parse(JSON.stringify(APP.S)); APP.S.roster={pilots:[],controllers:[]}; APP.S.t=null;
  APP.setEvents(['CSAR']); APP.generateGeneric(); APP.renderAll(); return APP.S.pr && [APP.S.pr.csar.length, APP.S.pr.med.length]; });
if(!pre||pre[0]!==2||pre[1]!==1) fail.push('prepared '+JSON.stringify(pre));
if(await page.isHidden('#tabpr')) fail.push('PR tab hidden');
await page.click('#tabpr'); await page.waitForTimeout(200);
const [d0]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('[data-prpack="ALL"]')]); await d0.saveAs('pr_pre.pdf');
const info=await page.evaluate(()=>{ APP.parseLines('2x HH-101\n1x AW169\n2x AH-129 Mangusta'); APP.tailor(); APP.renderAll();
  const P=APP.S.pr; return { resc:P.csar.map(c=>c.rescue.length+'/'+c.rescort.length), med:P.med.map(m=>!!m.flight), words:P.csar.flatMap(c=>[c.auth.wod,c.auth.password,c.auth.sarneg]), pub:JSON.stringify(APP.buildPayload(true).scenario) }; });
console.log(JSON.stringify({pre, resc:info.resc, med:info.med}));
for (const w of info.words) if (info.pub.includes('"'+w+'"')||info.pub.includes(w+' ')) fail.push('auth leaked: '+w);
if (/"surv"|"auth"|"lz"/.test(info.pub)) fail.push('survivor data leaked to public payload');
await page.click('#tabpr'); await page.waitForTimeout(200);
const [d1]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('[data-prpack="ALL"]')]); await d1.saveAs('pr_pack.pdf');
await page.click('[data-tab="export"]'); await page.waitForTimeout(200);
const [d2]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#mpdf')]); await d2.saveAs('pr_mp.pdf');
const [d3]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#pptbrief')]); await d3.saveAs('pr_br.pptx');
const pk=execSync('pdftotext pr_pack.pdf -').toString(), mp=execSync('pdftotext pr_mp.pdf -').toString();
for (const k of ['PR 11-line','Isolated personnel card','9-line MEDEVAC','CSARTF briefing','SARNEG','MAYDAY']) if(!pk.includes(k)) fail.push('pack missing '+k);
for (const w of info.words) if (mp.includes(w)) fail.push('auth in masterplan: '+w);
if(!/Personnel recovery/.test(mp)) fail.push('PR section missing in masterplan');
if(/ricerca|soccorso|personale isolato|quota|minaccia/i.test(pk)) fail.push('Italian text in PR pack');
console.log(fail.length?'"err": '+fail.join('; '):'checks ok');
console.log(errs.join('\n')||'no errors'); await b.close();})();
