const ENV = require('./_env.js');
// AIB: prepared fires, AIB pack, callsigns, injects never in pilot outputs
const { chromium } = require(ENV.PW); const { execSync } = require('child_process');
(async()=>{const b=await chromium.launch({executablePath:ENV.CHROME,args:['--no-sandbox']});
const ctx=await b.newContext({acceptDownloads:true,viewport:{width:1300,height:900}});const page=await ctx.newPage();const errs=[];
page.on('pageerror',e=>errs.push('PAGEERR '+e.message));
await page.route('**/*',r=>{const u=r.request().url();
 if(u.includes('leaflet.min.js'))return r.fulfill({path:ENV.LMOCK});
 if(u.includes('pptxgen'))return r.fulfill({path:ENV.PPTX});
 if(u.includes('pdf-lib.min.js'))return r.fulfill({path:ENV.PDFLIB});
 if(u.startsWith(ENV.BASE))return r.continue(); return r.abort();});
await page.goto(ENV.BASE+'/index.html#staff'); await page.waitForTimeout(800);
const fail=[];
const pre=await page.evaluate(()=>{ APP.S=JSON.parse(JSON.stringify(APP.S)); APP.S.roster={pilots:[],controllers:[]}; APP.S.t=null;
  APP.setEvents(['AIB']); APP.generateGeneric(); APP.renderAll(); return APP.S.aib && APP.S.aib.list.map(s=>s.req+'/'+s.water.kind); });
if(!pre||pre.length!==2) fail.push('prepared '+JSON.stringify(pre));
if(await page.isHidden('#tabaib')) fail.push('AIB tab hidden');
await page.click('#tabaib'); await page.waitForTimeout(200);
const [d0]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('[data-aibpack="ALL"]')]); await d0.saveAs('aib_pre.pdf');
const info=await page.evaluate(()=>{ APP.parseLines('2x CL-415\n1x AS350\n1x S-64\n1x NH90'); APP.tailor(); APP.renderAll();
  const L=APP.S.aib.list; return { fl:L.map(s=>s.flights.length), cs:L.flatMap(s=>Object.values(s.cs)), inj:L.flatMap(s=>s.injects.map(i=>i[1].slice(0,40))), fires:APP.S.t.objectives.filter(o=>o.type==='FIRE').length, pub:JSON.stringify(APP.buildPayload(true).scenario) }; });
console.log(JSON.stringify({pre, fl:info.fl, cs:info.cs, fires:info.fires}));
if(!info.cs.some(c=>/^CAN \d+/.test(c))) fail.push('no CAN callsign');
if(!info.cs.some(c=>/^I-[A-Z]{4} BAT/.test(c))) fail.push('no registration + BAT callsign');
if(info.fires<1) fail.push('no FIRE objective');
for (const t of info.inj) if (info.pub.includes(t)) fail.push('inject leaked to public payload');
if (/"injects"/.test(info.pub)) fail.push('injects key in public payload');
await page.click('#tabaib'); await page.waitForTimeout(200);
const [d1]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('[data-aibpack="ALL"]')]); await d1.saveAs('aib_pack.pdf');
await page.click('[data-tab="export"]'); await page.waitForTimeout(200);
const [d2]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#mpdf')]); await d2.saveAs('aib_mp.pdf');
const [d3]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#pptbrief')]); await d3.saveAs('aib_br.pptx');
const pk=execSync('pdftotext aib_pack.pdf -').toString(), mp=execSync('pdftotext aib_mp.pdf -').toString();
for (const k of ['Air support request (COAU)','DOS brief','Aircrew brief','Staff only','STS/FFR','OPAREA/','CAN ','blank form','Fire status log']) if(!pk.includes(k)) fail.push('pack missing '+k);
if(!/Aerial firefighting/.test(mp)) fail.push('AIB section missing in masterplan');
if(/Staff only|injects|Wind shift|Spot fire|Flare-up/.test(mp)) fail.push('injects in masterplan');
if(/incendio|soppressione|contenimento|bonifica|vento|quota|ritardante|fonte idrica/i.test(pk)) fail.push('Italian text in AIB pack');
console.log(fail.length?'"err": '+fail.join('; '):'checks ok');
console.log(errs.join('\n')||'no errors'); await b.close();})();
