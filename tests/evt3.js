const ENV = require('./_env.js');
const { chromium } = require(ENV.PW);
(async()=>{const b=await chromium.launch({executablePath:ENV.CHROME,args:['--no-sandbox']});
const ctx=await b.newContext({acceptDownloads:true,viewport:{width:1300,height:900}});const page=await ctx.newPage();const errs=[];
page.on('pageerror',e=>errs.push('PAGEERR '+e.message));
await page.route('**/*',r=>{const u=r.request().url();
 if(u.includes('leaflet.min.js'))return r.fulfill({path:ENV.LMOCK});
 if(u.includes('pptxgen'))return r.fulfill({path:ENV.PPTX});
 if(u.includes('pdf-lib.min.js'))return r.fulfill({path:ENV.PDFLIB});
 if(u.startsWith(ENV.BASE))return r.continue(); return r.abort();});
await page.goto(ENV.BASE+'/index.html#staff'); await page.waitForTimeout(800);
await page.evaluate(()=>{localStorage.clear();}); await page.reload(); await page.waitForTimeout(800);
await page.click('[data-tab="scenario"]'); await page.click('[data-wstep="ev"]');
await page.check('[data-evt="AIB"]'); await page.uncheck('[data-evt="MIX"]'); await page.waitForTimeout(200);
await page.click('[data-wstep="c2"]'); await page.setInputFiles('#posfile',ENV.FIX('pos.csv')); await page.waitForTimeout(400);
await page.evaluate(()=>{APP.S.meta.theatre='SA'; APP.renderAll();});
await page.click('[data-wstep="th"]'); await page.selectOption('#theatre','SA'); await page.waitForTimeout(300);
await page.screenshot({path:'w_s1.png',fullPage:true});
await page.click('[data-wstep="gen"]'); await page.click('#gen'); await page.waitForTimeout(300);
await page.evaluate(()=>{APP.S.roster={pilots:[],controllers:[{id:'c1',name:'Mario Rossi',pref:'APP'}]}; APP.parseLines('2x CL-415\n3x AW139\n1x AT-802'); APP.tailor();});
console.log(JSON.stringify(await page.evaluate(()=>({c2:APP.S.t.c2.map(c=>[c.role,c.cs,c.freq]), asp:APP.S.t.airspace.map(a=>a.type), sel:APP.S.c2sel.length}))));
await page.click('[data-tab="export"]'); await page.waitForTimeout(200);
await page.screenshot({path:'w_exp.png',fullPage:true});
const [d1]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#mpdf')]); await d1.saveAs('w_mp.pdf');
const [d2]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#pptbrief')]); await d2.saveAs('w_br.pptx');
const [d3]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#pptgen')]); await d3.saveAs('w_gen.pptx');
// toggle off contact+defs to test NIL
await page.uncheck('[data-mps="defs"]'); await page.waitForTimeout(100);
const [d4]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#mpdf')]); await d4.saveAs('w_mp2.pdf');
await page.click('#pubpreview'); await page.waitForTimeout(500); await page.screenshot({path:'w_pub.png',fullPage:true});
console.log(errs.join('\n')||'no errors'); await b.close();})();
