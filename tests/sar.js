const ENV = require('./_env.js');
// Civil SAR: prepared scenarios, SAR pack, assignment, solution never in pilot outputs
const { chromium } = require(ENV.PW); const { execSync } = require('child_process');
(async()=>{const b=await chromium.launch({executablePath:ENV.CHROME,args:['--no-sandbox']});
const ctx=await b.newContext({acceptDownloads:true,viewport:{width:1300,height:900}});const page=await ctx.newPage();const errs=[];
page.on('pageerror',e=>errs.push('PAGEERR '+e.message));
await page.route('**/*',r=>{const u=r.request().url();
 if(u.includes('leaflet.min.js'))return r.fulfill({path:ENV.LMOCK});
 if(u.includes('pptxgen'))return r.fulfill({path:ENV.PPTX});
 if(u.includes('pdf-lib.min.js'))return r.fulfill({path:ENV.PDFLIB});
 if(u.startsWith(ENV.BASE))return r.continue(); return r.abort();});
await page.goto(ENV.BASE+'/index.html#staff'); await page.waitForTimeout(800);
const fail=[];
const pre=await page.evaluate(()=>{ APP.S=JSON.parse(JSON.stringify(APP.S)); APP.S.roster={pilots:[],controllers:[]}; APP.S.t=null;
  APP.setEvents(['SAR']); APP.generateGeneric(); APP.renderAll(); return APP.S.sar && APP.S.sar.list.map(s=>s.env+'/'+s.pattern); });
if(!pre||pre.length!==2) fail.push('prepared '+JSON.stringify(pre));
if(await page.isHidden('#tabsar')) fail.push('SAR tab hidden');
await page.click('#tabsar'); await page.waitForTimeout(200);
const [d0]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('[data-sarpack="ALL"]')]); await d0.saveAs('sar_pre.pdf');
const info=await page.evaluate(()=>{ APP.parseLines('2x AW139\n1x PC-12\n1x H145'); APP.tailor(); APP.renderAll();
  const L=APP.S.sar.list; return { fl:L.map(s=>s.flights.length), osc:L.map(s=>s.osc), truth:L.map(s=>s.truth.join(',')), found:L.map(s=>s.found), pub:JSON.stringify(APP.buildPayload(true).scenario) }; });
console.log(JSON.stringify({pre, fl:info.fl, osc:info.osc}));
if(info.fl.reduce((a,b)=>a+b,0)<1) fail.push('no SAR flights assigned');
if(!info.osc.some(o=>/RESCUE INDIA (LIMA|MIKE)/.test(o))) fail.push('callsign');
for (const t of info.truth) if (info.pub.includes(t)) fail.push('truth leaked to public payload');
if (/"truth"|"found"|"datum"/.test(info.pub)) fail.push('SAR solution keys in public payload');
await page.click('#tabsar'); await page.waitForTimeout(200);
const [d1]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('[data-sarpack="ALL"]')]); await d1.saveAs('sar_pack.pdf');
await page.click('[data-tab="export"]'); await page.waitForTimeout(200);
const [d2]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#mpdf')]); await d2.saveAs('sar_mp.pdf');
const [d3]=await Promise.all([page.waitForEvent('download',{timeout:90000}),page.click('#pptbrief')]); await d3.saveAs('sar_br.pptx');
const pk=execSync('pdftotext sar_pack.pdf -').toString(), mp=execSync('pdftotext sar_mp.pdf -').toString();
for (const k of ['Search action plan','SAR briefing','SITREP','SAR debriefing','Distress card','Staff only','RESCUE INDIA','Commence search']) if(!pk.includes(k)) fail.push('pack missing '+k);
if(!/Search and rescue/.test(mp)) fail.push('SAR section missing in masterplan');
if(/Staff only|REAL POSITION|Distress card/.test(mp)) fail.push('solution in masterplan');
if(/ricerca|soccorso|dispers|quota|naufrag|escursionist/i.test(pk)) fail.push('Italian text in SAR pack');
console.log(fail.length?'"err": '+fail.join('; '):'checks ok');
console.log(errs.join('\n')||'no errors'); await b.close();})();
